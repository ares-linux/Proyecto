public void cargar_datos_tabla(int indice)
{
    this.t_año.setText(String.valueOf(this.Tabla1.getValueAt(indice,0)));
    this.T_marca.setText(String.valueOf(this.Tabla1.getValueAt(indice,1)));
    this.t_precio.setText(String.valueOf(this.Tabla1.getValueAt(indice,2)));
    this.t_nserie.setText(String.valueOf(this.Tabla1.getValueAt(indice,3)));
    this.t_foto.setText(String.valueOf(this.Tabla1.getValueAt(indice,4)));
    this.t_modelo.setText(String.valueOf(this.Tabla1.getValueAt(indice,5)));
    this.cargar_foto();
}
    private void b_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_eliminarActionPerformed
       fila= Tabla1.getSelectedRow();
         DefaultTableModel modelo2 = (DefaultTableModel) this.Tabla1.getModel();
         
         if(this.Tabla1.getRowCount()>0)
         {  
            modelo2.removeRow(fila);
            this.Tabla1.setModel(modelo2);
            fila = fila-1;
            if(fila<0)
            {
                limpiar_text();
            }
            else
            {
                cargar_datos_tabla(fila);
            } 
         }
     
    }//GEN-LAST:event_b_eliminarActionPerformed
 public void Editar_tabla()
   {
   DefaultTableModel modelo= (DefaultTableModel) this.Tabla1.getModel();
       modelo.setValueAt(this.t_año, fila, 0);
       modelo.setValueAt(this.T_marca, fila, 1);
       modelo.setValueAt(this.t_precio, fila, 2);
       modelo.setValueAt(this.t_nserie, fila, 3);
       modelo.setValueAt(this.t_foto, fila, 4);
       modelo.setValueAt(this.t_modelo, fila, 5);
       
      
       
       
    this.Tabla1.setModel(modelo);
   
   
   
   
   }
