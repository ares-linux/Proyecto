    private void b_puntoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_puntoActionPerformed
       String ruta= "";
      JFileChooser foto = new JFileChooser();
      FileNameExtensionFilter filtrado = new FileNameExtensionFilter("JPG,PNG & GIF","jpg,","png","gif");
      foto.setFileFilter(filtrado);
      
      int respuesta = foto.showOpenDialog(this);
      
      if (respuesta == foto.APPROVE_OPTION)
      {
          ruta = foto.getSelectedFile().getPath();
          this.l_foto.setText(ruta);
          
          ImageIcon img = new ImageIcon(ruta);
          Icon icono = new ImageIcon(img.getImage().getScaledInstance(this.l_foto.getWidth(),this.l_foto.getHeight(),Image.SCALE_DEFAULT));
         this.l_foto.setIcon(icono);
    }   
     
      
      
      
    }//GEN-LAST:event_b_puntoActionPerformed
