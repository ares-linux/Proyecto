    private void b_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_eliminarActionPerformed
     //Botoneliminar
     int fila = this.tabla_ventas.getSelectedRow();
     DefaultTableModel modelo=(DefaultTableModel) this.tabla_ventas.getModel();
     if (fila>=0)
     {
        modelo.removeRow(fila);
        if(tabla_ventas.getRowCount()>0)
        {
            calcular_subtotal();
        }
        else{
        
        t_iva.setText("0");
        t_subtotal.setText("0");
        t_total.setText("0");
        }
     }
     else
     {
     JOptionPane.showMessageDialog(null,"Seleccionar Fila");
     
     }
    
    }//GEN-LAST:event_b_eliminarActionPerformed
public void limpiar_venta()
{
    DefaultTableModel modelo=(DefaultTableModel) this.tabla_ventas.getModel();
    int a = this.tabla_ventas.getRowCount()-1;
    for (int i = a; i>=0;i-- )
    {
        modelo.removeRow(i);
    }        
        this.tabla_ventas.setModel(modelo);
        calcular_subtotal();
}   
        
        
        
        
        
        
