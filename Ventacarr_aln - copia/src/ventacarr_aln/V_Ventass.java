public void calcular_monto()
{

   float cant,precio,monto;
    
    cant= Float.parseFloat(t_cantidad.getText());
    precio= Float.parseFloat(t_preciouni.getText());
    monto= cant* precio;
    t_monto.setText(Float.toString(monto));




}
