 public void limpiar_text()
         {
            this.t_idcliente.setText("");
            this.t_nombre.setText("");
            this.t_apellido.setText("");
            this.t_fechanac.setText("");
            this.t_direccion.setText("");
            this.t_telefono.setText("");
            this.t_foto.setText("D:\\nofoto.jpg");
            this.cargar_foto();
         }
 
 
 
