    private void b_nuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_nuevoActionPerformed
       if (b_nuevo.getText()=="Nuevo")
       {
          b_nuevo.setText("Guardar");
          limpiar_text();
          this.t_idcliente.requestFocus();
          b_eliminar.setEnabled(false);
          b_editar.setEnabled(false);
          b_buscar.setEnabled(false);
          desbloquear_text();
        
       }
       else
        {
         if(t_idcliente.getText().trim().isEmpty()|| t_nombre.getText().trim().isEmpty()|| t_apellido.getText().trim().isEmpty()||t_direccion.getText().trim().isEmpty()||t_foto.getText().trim().isEmpty()||t_telefono.getText().trim().isEmpty()||t_fechanac.getText().trim().isEmpty())
         
          {    
              
              
          }
        
        
       
       else
       {
       b_nuevo.setText("Nuevo");
       llenar_tabla();
       b_eliminar.setEnabled(true);
       b_editar.setEnabled(true);
       b_buscar.setEnabled(true);
       b_punto.setEnabled(true);
       bloquear_text();
        
       }
        }
    }//GEN-LAST:event_b_nuevoActionPerformed

    
    
    public void Editar_tabla()
   {
   DefaultTableModel modelo= (DefaultTableModel) this.Tabla2.getModel();
       modelo.setValueAt(this.t_idcliente, fila, 0);
       modelo.setValueAt(this.t_nombre, fila, 1);
       modelo.setValueAt(this.t_apellido, fila, 2);
       modelo.setValueAt(this.t_direccion, fila, 3);
       modelo.setValueAt(this.t_foto, fila, 4);
       modelo.setValueAt(this.t_telefono, fila, 5);
       modelo.setValueAt(this.t_fechanac, fila, 6);
       
      
       
       
    this.Tabla2.setModel(modelo);
   
   
   
   
   }
    
    public void cargar_datos_tabla(int indice)
{
    this.t_idcliente.setText(String.valueOf(this.Tabla2.getValueAt(indice,0)));
    this.t_nombre.setText(String.valueOf(this.Tabla2.getValueAt(indice,1)));
    this.t_apellido.setText(String.valueOf(this.Tabla2.getValueAt(indice,2)));
    this.t_fechanac.setText(String.valueOf(this.Tabla2.getValueAt(indice,3)));
    this.t_telefono.setText(String.valueOf(this.Tabla2.getValueAt(indice,4)));
    this.t_foto.setText(String.valueOf(this.Tabla2.getValueAt(indice,5)));
    this.cargar_foto();
}
