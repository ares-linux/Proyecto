       public void limpiar_text()
         {
            this.T_id.setText("");
            this.T_nom.setText("");
            this.T_ape.setText("");
            this.T_fechanac.setText("");
            this.T_email.setText("");
            this.T_tel.setText("");
            this.T_foto.setText("D:\\nofoto.jpg");
            this.cargar_foto();




         }
   public void llenar_tabla()
   {
       
   String [] info =new String[7];
   info [0]=this.T_id.getText();
   info [1]=this.T_nom.getText();
   info [2]=this.T_ape.getText();
   info [3]=this.T_fechanac.getText();
   info [4]=this.T_email.getText();
   info [5]=this.T_foto.getText();
   info [6]=this.T_tel.getText();
   
    DefaultTableModel modelo= (DefaultTableModel) this.Tabla2.getModel();
            modelo.addRow(info);
            this.Tabla2.setModel(modelo);

   }
   
   public void Editar_tabla()
   {
   DefaultTableModel modelo= (DefaultTableModel) this.Tabla2.getModel();
       modelo.setValueAt(this.T_id, fila, 0);
       modelo.setValueAt(this.T_nom, fila, 1);
       modelo.setValueAt(this.T_ape, fila, 2);
       modelo.setValueAt(this.T_fechanac, fila, 3);
       modelo.setValueAt(this.T_email, fila, 4);
       modelo.setValueAt(this.T_foto, fila, 5);
       modelo.setValueAt(this.T_tel, fila, 6);
      
       
       
    this.Tabla2.setModel(modelo);
   
   
   
   
   }
   
   
   
   
   
